    /// <summary>True when the glyph has a pixel at (column, row) — both
    /// zero-based, column 0 leftmost. Unknown characters render blank.</summary>
    public static bool HasPixel(char character, int column, int row)
    {
        if (column < 0 || column >= GlyphWidth || row < 0 || row >= GlyphHeight
            || !Glyphs.TryGetValue(char.ToUpperInvariant(character), out byte[]? glyph))
        {
            return false;
        }

        return (glyph[row] & (1 << (GlyphWidth - 1 - column))) != 0;
    }
}
