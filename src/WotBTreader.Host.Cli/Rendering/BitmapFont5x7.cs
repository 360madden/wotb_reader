namespace WotBTreader.Host.Cli.Rendering;

/// <summary>
/// A tiny 5x5 bitmap font (uppercase A-Z, digits, and a small punctuation
/// set) for schematic labels in the offline frame preview. Each glyph is 5
/// bytes (one per row); bit (4 - column) of each byte is the pixel at that
/// column, so the most significant bit of the value is the leftmost pixel.
/// No external font dependency keeps the preview pure-BCL and deterministic.
/// </summary>
public static class BitmapFont5x7
{
    /// <summary>Glyph width in pixels (fixed advance).</summary>
    public const int GlyphWidth = 5;

    /// <summary>Glyph height in pixels.</summary>
    public const int GlyphHeight = 5;

